export function getLocalizedDepartment(dept, lang = 'en') {
  if (!dept) return '';
  return DEPARTMENT_TRANSLATIONS[dept]?.[lang] || dept;
}

export function getLocalizedCategory(category, lang = 'en') {
  if (!category) return '';
  return CATEGORY_TRANSLATIONS[category]?.[lang] || category;
}

export function getLocalizedStatus(status, lang = 'en') {
  if (!status) return '';
  const normalized = status.toUpperCase().replace(/\s+/g, '_');
  return STATUS_TRANSLATIONS[normalized]?.[lang] || STATUS_TRANSLATIONS[status]?.[lang] || status;
}

export function getLocalizedPriority(priority, lang = 'en') {
  if (!priority) return '';
  const normalized = priority.toUpperCase();
  return PRIORITY_TRANSLATIONS[normalized]?.[lang] || priority;
}

export function getLocalizedChannel(channel, lang = 'en') {
  if (!channel) return '';
  const normalized = channel.toUpperCase();
  return CHANNEL_TRANSLATIONS[normalized]?.[lang] || channel;
}
